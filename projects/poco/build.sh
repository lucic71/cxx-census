#!/bin/bash -eu

cmake -S "$SRC/poco" -B "$BUILD" -G Ninja -DCMAKE_BUILD_TYPE=Release -DCMAKE_EXPORT_COMPILE_COMMANDS=ON \
  -DENABLE_NETSSL=OFF -DENABLE_CRYPTO=OFF -DENABLE_JWT=OFF -DENABLE_DATA_MYSQL=OFF -DENABLE_DATA_POSTGRESQL=OFF \
  -DENABLE_DATA_ODBC=OFF -DENABLE_MONGODB=ON -DENABLE_REDIS=ON -DENABLE_TESTS=OFF
cmake --build "$BUILD" -j "$(nproc)"
