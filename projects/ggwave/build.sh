#!/bin/bash -eu

cmake -S "$SRC/ggwave" -B "$BUILD" -G Ninja -DCMAKE_BUILD_TYPE=Release -DCMAKE_EXPORT_COMPILE_COMMANDS=ON \
  -DCMAKE_CXX_FLAGS="$CXXFLAGS -fno-exceptions" \
  -DBUILD_SHARED_LIBS=OFF -DGGWAVE_SUPPORT_SDL2=OFF -DGGWAVE_BUILD_EXAMPLES=OFF -DGGWAVE_BUILD_TESTS=ON
cmake --build "$BUILD" -j "$(nproc)"
